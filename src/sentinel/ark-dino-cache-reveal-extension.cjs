function revealFrame(record, stage) {
  const roll = record.roll || {};
  const visibleSpecies = stage >= 1 ? `🦖 **${clean(roll.species, 100)}**` : '████████████';
  const visibleVariant = stage >= 2 ? `🧬 **${formatVariant(roll.variant)}**` : '████████';
  const visibleLevel = stage >= 3 ? `📈 **Level ${Number(roll.level || 0)}**` : '██████';
  const sexLine = roll.sex ? (stage >= 4 ? `⚥ **${clean(roll.sex, 40)}**` : '██████') : '';
  const done = stage >= (roll.sex ? 4 : 3);
  return {
    embeds: [{
      title: done ? `🎉 ${cacheLabel(record.cacheId)} Revealed` : `🎰 Opening ${cacheLabel(record.cacheId)}…`,
      description: [
        `**Creature**\n${visibleSpecies}`,
        `**Variant**\n${visibleVariant}`,
        `**Level**\n${visibleLevel}`,
        sexLine ? `**Sex**\n${sexLine}` : '',
        done ? '\n📦 **Delivery queued** for your linked ARK account.' : ''
      ].filter(Boolean).join('\n\n'),
      color: done ? 0x2ecc71 : 0xf1c40f,
      footer: { text: `Reward ID ${record.id} • result was locked before reveal` }
    }],
    components: [],
    allowedMentions: { parse: [] }
  };
}

function inventoryPayload(records = []) {
  const sealed = records.filter((record) => record.revealStatus !== 'revealed' && record.state === 'sealed');
  const recent = records.filter((record) => record.revealStatus === 'revealed' || record.deliveryStatus === 'delivered').slice(0, 8);
  const lines = [];
  if (sealed.length) {
    lines.push('**🔒 Sealed**');
    for (const record of sealed.slice(0, 10)) lines.push(`• ${cacheLabel(record.cacheId)} — \`${record.id}\``);
  } else lines.push('**🔒 Sealed**\nNone');
  lines.push('', '**Recent**');
  if (!recent.length) lines.push('No revealed caches yet.');
  for (const record of recent) {
    const roll = record.roll || {};
    lines.push(`${stateEmoji(record)} **${formatVariant(roll.variant)} ${clean(roll.species, 70)}** · Lv.${Number(roll.level || 0)} · ${cacheLabel(record.cacheId)}`);
  }
  const revealButtons = sealed.slice(0, 5).map((record, index) => ({
    type: 2,
    style: 1,
    label: `Reveal ${index + 1}`,
    custom_id: `${PREFIX}:reveal:${record.id}`
  }));
  return {
    embeds: [{
      title: '🎁 My Dino Caches',
      description: lines.join('\n').slice(0, 3900),
      color: 0x5865f2,
      footer: { text: 'Sealed rewards are already rolled; revealing never rerolls them.' }
    }],
    components: revealButtons.length ? [{ type: 1, components: revealButtons }] : [],
    allowedMentions: { parse: [] }
  };
}

function extractEosId(value, depth = 0) {
  if (!value || depth > 5) return '';
  if (typeof value !== 'object') return '';
  const directKeys = ['eosId', 'eos_id', 'arkEosId', 'ark_eos_id', 'eosPlayerId', 'eos_player_id'];
  for (const key of directKeys) {
    const candidate = String(value[key] || '').trim();
    if (/^[A-Za-z0-9_-]{8,96}$/.test(candidate)) return candidate;
  }
  for (const [key, nested] of Object.entries(value)) {
    if (!nested || typeof nested !== 'object') continue;
    if (!/(ark|eos|game|link|account|identity|profile)/i.test(key)) continue;
    const found = extractEosId(nested, depth + 1);
    if (found) return found;
  }
  return '';
}

async function resolveLinkedEosId(backend, discordUserId) {
  const response = await backend.accountByDiscord(String(discordUserId));
  if (!response?.ok) throw new Error('Link your Discord account to ARK before purchasing a Dino Cache.');
  const eosId = extractEosId(response.account || response);
  if (!eosId) throw new Error('Your Nexus account is linked, but no ARK EOS player ID is attached yet.');
  return eosId;
}

function shouldAnnounce(record) {
  const roll = record?.roll || {};
  const minRarity = String(process.env.NEXUS_DINO_CACHE_ANNOUNCE_MIN_RARITY || 'rare').toLowerCase();
  const minRank = Object.hasOwn(RARITY_RANK, minRarity) ? RARITY_RANK[minRarity] : RARITY_RANK.rare;
  const rarityHit = (RARITY_RANK[String(roll.rarity || '').toLowerCase()] ?? -1) >= minRank;
  const levelHit = Number(roll.level || 0) >= Math.max(1, Number(process.env.NEXUS_DINO_CACHE_ANNOUNCE_LEVEL || 295) || 295);
  const announceVariants = new Set(String(process.env.NEXUS_DINO_CACHE_ANNOUNCE_VARIANTS || 'x,s').toLowerCase().split(',').map((item) => item.trim()).filter(Boolean));
  const variantHit = announceVariants.has(String(roll.variant || '').toLowerCase());
  return rarityHit || levelHit || variantHit;
}

function clusterChatChannelId(config) {
  return String(
    process.env.NEXUS_ARK_CLUSTER_CHAT_CHANNEL_ID
    || config?.discord?.arkClusterChatChannelId
    || config?.discord?.clusterChatChannelId
    || config?.modules?.ark?.clusterChatChannelId
    || ''
  ).trim();
}

async function announceReveal(client, config, service, record, displayName) {
  if (!record || record.announcementStatus === 'sent' || record.announcementStatus === 'not_required') return;
  if (!shouldAnnounce(record)) {
    service.store.transition(record.id, record.state, { announcementStatus: 'not_required' });
    return;
  }
  const channelId = clusterChatChannelId(config);
  if (!channelId) {
    console.warn('[Nexus Sentinal] Dino Cache reveal qualifies for Cluster Chat, but NEXUS_ARK_CLUSTER_CHAT_CHANNEL_ID is not configured.');
    return;
  }
  const channel = await client.channels.fetch(channelId).catch(() => null);
  if (!channel?.isTextBased?.()) throw new Error('Configured ARK Cluster Chat channel is not text-capable.');

  service.store.transition(record.id, record.state, { announcementStatus: 'sending' });
  try {
    const roll = record.roll || {};
    const message = await channel.send({
      content: [
        '🎉 **CACHE REVEAL**',
        `**${clean(displayName, 80) || 'A survivor'}** opened a **${cacheLabel(record.cacheId)}**!`,
        `🦖 **${formatVariant(roll.variant)} ${clean(roll.species, 100)}** · 📈 **Lv.${Number(roll.level || 0)}**${roll.sex ? ` · **${clean(roll.sex, 30)}**` : ''}`
      ].join('\n'),
      allowedMentions: { parse: [] }
    });
    service.store.transition(record.id, record.state, {
      announcementStatus: 'sent',
      announcementMessageId: String(message.id)
    });
  } catch (error) {
    service.store.transition(record.id, record.state, { announcementStatus: 'pending' });
    throw error;
  }
}

async function registerCommands(guild) {
  const wanted = [shopCommand(), inventoryCommand()];
  const existing = await guild.commands.fetch();
  for (const command of wanted) {
    const current = existing.find((item) => item.name === command.name);
    if (current) await guild.commands.edit(current, command.toJSON());
    else await guild.commands.create(command.toJSON());
  }
}

function installArkDinoCacheRevealExtension(options = {}) {
  if (Client.prototype[INSTALLED]) return;
  Client.prototype[INSTALLED] = true;
  const config = loadConfig();
  const backend = options.backend || new BackendClient(config);
  const service = options.service || new SealedDinoCacheService({ prefix: options.prefix || 'ARK_GEN1' });
  const originalLogin = Client.prototype.login;

  Client.prototype.login = function nexusDinoCacheRevealLogin(...args) {
    const client = this;
    if (!client[BOUND]) {
      client[BOUND] = true;

      client.once(Events.ClientReady, () => {
        const guildId = String(config.discord?.guildId || '');
        void client.guilds.fetch(guildId)
          .then((guild) => registerCommands(guild))
          .then(() => console.log('[Nexus Sentinal] /dinocache and /caches sealed-reveal commands ready.'))
          .catch((error) => console.error('[Nexus Sentinal] Dino Cache command registration failed:', error));

        const intervalSeconds = Math.max(15, Number(process.env.NEXUS_DINO_CACHE_DELIVERY_RETRY_SECONDS || 30) || 30);
        const processQueue = () => void service.processDeliveryQueue({ limit: 10 })
          .then((results) => {
            const delivered = results.filter((item) => item?.ok && !item?.alreadyDelivered).length;
            if (delivered) console.log(`[Nexus Sentinal] Dino Cache delivery queue delivered ${delivered} reward(s).`);
          })
          .catch((error) => console.warn('[Nexus Sentinal] Dino Cache delivery queue:', clean(error?.message || error, 240)));
        processQueue();
        client[DELIVERY_TIMER] = setInterval(processQueue, intervalSeconds * 1000);
        client[DELIVERY_TIMER].unref?.();
      });

      client.on(Events.InteractionCreate, (interaction) => {
        if (String(interaction.guildId || '') !== String(config.discord?.guildId || '')) return;

        if (interaction.isChatInputCommand?.() && (interaction.commandName === 'dinocache' || interaction.commandName === 'caches')) {
          void (async () => {
            if (interaction.commandName === 'caches' || interaction.options.getSubcommand(false) === 'inventory') {
              const records = service.store.listForDiscord(String(interaction.user.id), { limit: 30 });
              await interaction.reply({ ...inventoryPayload(records), flags: MessageFlags.Ephemeral });
              return;
            }
            await interaction.reply({ ...shopPayload(), flags: MessageFlags.Ephemeral });
          })().catch((error) => interaction.reply({ content: `Dino Cache error: ${clean(error?.message || error, 220)}`, flags: MessageFlags.Ephemeral }).catch(() => {}));
          return;
        }

        if (interaction.isStringSelectMenu?.() && interaction.customId === SHOP_SELECT) {
          const cacheId = String(interaction.values?.[0] || '');
          void interaction.update(cacheDetailPayload(cacheId)).catch(() => {});
          return;
        }

        if (!interaction.isButton?.()) return;
        const customId = String(interaction.customId || '');
        if (!customId.startsWith(`${PREFIX}:`)) return;

        void (async () => {
          const [, action, value = ''] = customId.split(':');
          if (action === 'back') return interaction.update(shopPayload());
          if (action === 'detail') return interaction.update(cacheDetailPayload(value));
          if (action === 'odds') return interaction.update(oddsPayload(value));
          if (action === 'later') {
            return interaction.update({
              embeds: [{
                title: '🔒 Dino Cache Saved',
                description: 'Your reward remains sealed and unchanged. Use **/caches** whenever you want to reveal it.',
                color: 0x5865f2
              }],
              components: [],
              allowedMentions: { parse: [] }
            });
          }
          if (action === 'buy') {
            await interaction.deferUpdate();
            const eosId = await resolveLinkedEosId(backend, interaction.user.id);
            const result = await service.sealPurchase({
              discordUserId: interaction.user.id,
              eosId,
              cacheId: value,
              purchaseSource: 'discord-button'
            });
            if (!result.ok) {
              const message = result.reason === 'insufficient-points'
                ? `You need **${formatPoints(result.price)}** points but currently have **${formatPoints(result.balance)}**.`
                : result.reason === 'cooldown'
                  ? `That cache is on cooldown for another **${Math.ceil(Number(result.remainingSeconds || 0) / 60)} minute(s)**.`
                  : 'The purchase could not be completed.';
              return interaction.editReply({ embeds: [{ title: '⚠️ Cache Purchase Blocked', description: message, color: 0xe74c3c }], components: [], allowedMentions: { parse: [] } });
            }
            return interaction.editReply(sealedPayload(result.record, result.balanceAfter));
          }
          if (action === 'reveal') {
            await interaction.deferUpdate();
            const record = service.reveal(value, interaction.user.id);
            const maxStage = record.roll?.sex ? 4 : 3;
            for (let stage = 0; stage <= maxStage; stage += 1) {
              await interaction.editReply(revealFrame(record, stage));
              if (stage < maxStage) await sleep(Math.max(350, Number(process.env.NEXUS_DINO_CACHE_REVEAL_STEP_MS || 700) || 700));
            }
            const displayName = interaction.member?.displayName || interaction.user.globalName || interaction.user.username;
            void announceReveal(client, config, service, record, displayName)
              .catch((error) => console.warn('[Nexus Sentinal] Dino Cache Cluster Chat announcement:', clean(error?.message || error, 240)));
            void service.deliver(record.id)
              .then((delivery) => {
                if (!delivery.ok) console.log(`[Nexus Sentinal] Dino Cache ${record.id} remains queued for delivery.`);
              })
              .catch((error) => console.warn(`[Nexus Sentinal] Dino Cache ${record.id} delivery:`, clean(error?.message || error, 240)));
            return;
          }
        })().catch(async (error) => {
          const payload = { embeds: [{ title: '⚠️ Dino Cache Error', description: clean(error?.message || error, 300), color: 0xe74c3c }], components: [], allowedMentions: { parse: [] } };
          if (interaction.deferred || interaction.replied) await interaction.editReply(payload).catch(() => {});
          else await interaction.reply({ ...payload, flags: MessageFlags.Ephemeral }).catch(() => {});
        });
      });
    }
    return originalLogin.apply(this, args);
  };
}

