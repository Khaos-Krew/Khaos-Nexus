function cacheDetailPayload(cacheId) {
  const id = String(cacheId || '').toLowerCase();
  const pool = CACHE_POOLS[id];
  if (!pool) throw new Error('That Dino Cache is not currently available.');
  const names = (pool.entries || []).map((entry) => entry.name);
  const preview = names.slice(0, 8).join(' • ') + (names.length > 8 ? ` • +${names.length - 8} more` : '');
  const cooldown = Number(pool.cooldownHours || 0);
  return {
    embeds: [{
      title: `🎁 ${cacheLabel(id)}`,
      description: [
        preview || 'Curated tame pool',
        '',
        `💰 **${formatPoints(pool.price)} ArkShop Points**`,
        cooldown > 0 ? `⏱ **Cooldown:** ${cooldown} hours` : '',
        '',
        '**Rolls**',
        '• Species from this cache’s approved pool',
        '• Normal / X / S only where a verified form exists',
        '• Level generated by the cache engine',
        '',
        '🔒 The exact result is committed at purchase time and remains hidden until reveal.'
      ].filter(Boolean).join('\n'),
      color: id === 'apex' ? 0xe67e22 : 0x5865f2,
      footer: { text: 'Purchase and reveal stay private • qualifying result goes to Cluster Chat' }
    }],
    components: [
      { type: 1, components: [
        { type: 2, style: 3, label: `Buy • ${formatPoints(pool.price)}`, custom_id: `${PREFIX}:buy:${id}` },
        { type: 2, style: 2, label: 'View Odds', custom_id: `${PREFIX}:odds:${id}` },
        { type: 2, style: 2, label: 'Back', custom_id: SHOP_BACK }
      ] }
    ],
    allowedMentions: { parse: [] }
  };
}

function oddsPayload(cacheId) {
  const id = String(cacheId || '').toLowerCase();
  const pool = CACHE_POOLS[id];
  if (!pool) throw new Error('That Dino Cache is not currently available.');
  const grouped = new Map();
  for (const rarity of RARITY_ORDER) grouped.set(rarity, []);
  for (const entry of pool.entries || []) {
    const key = grouped.has(entry.rarity) ? entry.rarity : 'common';
    grouped.get(key).push(entry.name);
  }
  const fields = [...grouped.entries()]
    .filter(([, names]) => names.length)
    .map(([rarity, names]) => ({ name: titleCase(rarity), value: names.join(' • ').slice(0, 1024), inline: false }));
  return {
    embeds: [{
      title: `🎲 ${cacheLabel(id)} • Roll Pool`,
      description: 'The shop card stays compact; the configured pool is shown here. Exact weights continue to come from the cache engine and are not changed by this UI build.',
      color: 0x3498db,
      fields,
      footer: { text: 'Normal / X / S are only considered when that exact safe variant is configured.' }
    }],
    components: [{ type: 1, components: [
      { type: 2, style: 3, label: `Buy • ${formatPoints(pool.price)}`, custom_id: `${PREFIX}:buy:${id}` },
      { type: 2, style: 2, label: 'Back to Cache', custom_id: `${PREFIX}:detail:${id}` }
    ] }],
    allowedMentions: { parse: [] }
  };
}

