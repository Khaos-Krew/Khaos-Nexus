function clean(value, max = 180) {
  return String(value ?? '').replace(/[\r\n]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, max);
}
function titleCase(value) {
  return String(value || '').split(/[-_\s]+/).filter(Boolean).map((part) => part[0]?.toUpperCase() + part.slice(1)).join(' ');
}
function cacheLabel(cacheId) {
  const id = String(cacheId || '').toLowerCase();
  if (id === 'deepcave') return 'Deep Cave Cache';
  return `${titleCase(id)} Cache`;
}
function sleep(ms) { return new Promise((resolve) => setTimeout(resolve, ms)); }
function formatPoints(value) { return Number(value || 0).toLocaleString('en-US'); }
function formatVariant(value) {
  const variant = String(value || 'normal').toLowerCase();
  return variant === 'normal' ? 'Normal' : variant.toUpperCase();
}
function stateEmoji(record) {
  if (record?.deliveryStatus === 'delivered') return '✅';
  if (record?.revealStatus === 'revealed') return '📦';
  return '🔒';
}

